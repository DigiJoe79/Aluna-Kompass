/**
 * `description`: zweite Zeile unter der Beschriftung. `disabledReason`
 * deaktiviert den Eintrag und nennt den Grund als zweite Zeile; der Eintrag
 * bleibt fokussierbar (`aria-disabled`, Base UI) und liest den Grund über
 * `aria-describedby` vor. Grund in `muted`, nicht halb durchsichtig, damit er
 * lesbar bleibt (Ordnerbaum, HANDOFF § 3.8).
 */
function DropdownMenuItem({
  className,
  inset,
  variant = "default",
  onSelect,
  onClick,
  description,
  disabledReason,
  disabled,
  children,
  ...props
}: MenuPrimitive.Item.Props & {
  inset?: boolean
  variant?: "default" | "destructive"
  onSelect?: (event: React.MouseEvent<HTMLElement>) => void
  description?: React.ReactNode
  disabledReason?: string
}) {
  const hint = disabledReason ?? description
  const hintId = React.useId()
  const hasHint = hint !== undefined && hint !== null && hint !== ""
  return (
    <MenuPrimitive.Item
      data-slot="dropdown-menu-item"
      data-inset={inset}
      data-variant={variant}
      data-reason={disabledReason ? "" : undefined}
      disabled={disabled || !!disabledReason}
      aria-describedby={hasHint ? hintId : undefined}
      onClick={(e) => {
        onClick?.(e)
        onSelect?.(e)
      }}
      className={cn(
        "group/dropdown-menu-item relative flex cursor-default items-center gap-1.5 rounded-md px-1.5 py-1 text-sm outline-hidden select-none focus:bg-hover focus:text-ink not-data-[variant=destructive]:focus:**:text-ink data-inset:pl-7 data-[variant=destructive]:text-error data-[variant=destructive]:focus:bg-error-bg data-[variant=destructive]:focus:text-error dark:data-[variant=destructive]:focus:bg-error-bg data-disabled:pointer-events-none data-disabled:opacity-50 [&_svg]:pointer-events-none [&_svg]:shrink-0 [&_svg:not([class*='size-'])]:size-4 data-[variant=destructive]:*:[svg]:text-error",
        // Zweite Zeile: Der Eintrag bricht um, die Beschreibung steht unter der Beschriftung, nicht unter dem Symbol.
        hasHint && "flex-wrap gap-y-px [&:has(>svg)>[data-slot=dropdown-menu-item-description]]:pl-[22px]",
        disabledReason && "data-disabled:text-disabled-ink data-disabled:opacity-100",
        className
      )}
      {...props}
    >
      {children}
      {hasHint ? (
        // Nur über `aria-describedby` vorgelesen; der Name bleibt die Beschriftung.
        <span
          id={hintId}
          aria-hidden
          data-slot="dropdown-menu-item-description"
          className="basis-full text-xs leading-[1.4] text-muted-ink"
        >
          {hint}
        </span>
      ) : null}
    </MenuPrimitive.Item>
  )
}

